/**
 * Downloads a text page over HTTPS trusting ONLY the pinned Russian Trusted Root CA.
 * Used solely for metro.spb.ru; other sources go through the regular fetch().
 */
export const httpsGetTextPinnedRussianCa = (url: string, timeoutMs: number): Promise<string> =>
  new Promise((resolve, reject) => {
    const req = https.get(
      url,
      {
        // Accept is mandatory for /map1/* paths (the site's WAF answers 477 without it);
        // sent unconditionally in case the filter expands to the rest of the site
        headers: { 'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64)', Accept: '*/*' },
        ca: RUSSIAN_TRUSTED_ROOT_CA_PEM,
        timeout: timeoutMs,
      },
      (res) => {
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`HTTP ${res.statusCode} ${res.statusMessage ?? ''} while requesting ${url}`));
          return;
        }
        const chunks: Buffer[] = [];
        res.on('data', (c: Buffer) => chunks.push(c));
        res.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
        res.on('error', reject);
      },
    );
    req.on('timeout', () => req.destroy(new Error(`Timeout after ${timeoutMs} ms while requesting ${url}`)));
    req.on('error', reject);
  });
